/*
 * The Circle modal's theme, checked without being able to open the modal.
 *
 * The modal is an iframe on pw-auth.circle.com, so it cannot be inspected from
 * here and cannot be opened at all until email delivery is configured on
 * Circle's side. What CAN be checked is everything we hand it, and the ways
 * that payload can be silently wrong:
 *
 *   - an icon whose data URI does not decode is a broken image in the modal
 *   - an icon left as `currentColor` is INVISIBLE there, because the iframe
 *     inherits no colour from this app — this is the easy mistake, since
 *     markSvg() defaults to currentColor and every in-app use relies on it
 *   - a near-black icon on a near-black modal is the same failure by other
 *     means, so every colour is contrast-checked against the surface
 *
 * Key names are not checked here: circle-theme.ts is typed against the SDK's
 * own ThemeColor and Resources, so a typo is already a build error.
 *
 * Run from web/:  npm run check:theme
 */
import { readFileSync } from "node:fs";

const src = readFileSync("lib/wallet/circle-theme.ts", "utf8");

/** sRGB relative luminance, per WCAG 2.1. */
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
}

// ------------------------------------------------------------------ icons
// The generated URIs are built at runtime, so rebuild them the same way the
// module does rather than trying to import a .ts with a React-flavoured graph.
const SURFACE = "#0a0a0a";

const rows = [];
let bad = 0;

// Rebuild each icon by evaluating the same helpers the module defines.
const CREAM = "#f0eee9";
const CREAM_SOFT = "#b9b5ab";
const WARN_ON_DARK = "#f5a524";

function svgUri(svg) {
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}
function stroke(path, colour = CREAM, width = 1.75) {
  return svgUri(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" ` +
      `width="24" height="24" fill="none" ` +
      `stroke="${colour}" stroke-width="${width}" stroke-linecap="square">${path}</svg>`,
  );
}

// Same shapes as the module, kept in one place so a divergence shows up as a
// mismatch in the source scan below rather than as a passing check of nothing.
const icons = {
  naviClose: stroke('<path d="M5 5 L19 19"/><path d="M19 5 L5 19"/>'),
  naviBack: stroke('<path d="M14 5 L7 12 L14 19"/>'),
  dropdownArrow: stroke('<path d="M6 9.5 L12 15.5 L18 9.5"/>'),
  selectCheckMark: stroke('<path d="M5 12.5 L10 17.5 L19 6.5"/>'),
  errorInfo: stroke(
    '<circle cx="12" cy="12" r="9"/><path d="M12 7 L12 13"/><path d="M12 16.5 L12 17"/>',
    WARN_ON_DARK,
  ),
  tipIcon: stroke(
    '<circle cx="12" cy="12" r="9"/><path d="M12 11 L12 17"/><path d="M12 7 L12 7.5"/>',
    CREAM_SOFT,
  ),
};

for (const [name, uri] of Object.entries(icons)) {
  const decoded = decodeURIComponent(uri.replace(/^data:image\/svg\+xml;utf8,/, ""));
  const wellFormed = decoded.startsWith("<svg") && decoded.trimEnd().endsWith("</svg>");
  const drawable = /<(path|circle|rect|line|polyline)\b/.test(decoded);
  const colour = /stroke="(#[0-9a-fA-F]{6})"/.exec(decoded)?.[1];
  const inherits = /currentColor/.test(decoded);
  const ratio = colour ? contrast(colour, SURFACE) : 0;

  // 3:1 is the WCAG threshold for a non-text graphic.
  /*
   * An icon with no intrinsic size renders at the browser's 150x150 fallback
   * when nothing sizes it, and we do not control the img tag inside Circle's
   * iframe. This was true of every stroke icon until it was measured.
   */
  const sized = /width="\d+"/.test(decoded) && /height="\d+"/.test(decoded);

  const ok = wellFormed && drawable && !inherits && sized && ratio >= 3;
  if (!ok) bad++;
  rows.push({
    icon: name,
    decodes: wellFormed,
    drawable,
    sized,
    "currentColor?": inherits,
    colour: colour ?? "—",
    "vs #0a0a0a": ratio ? `${ratio.toFixed(1)}:1` : "—",
    ok,
  });
}

// The mark is generated by markSvg(); check the source passes it a real colour
// rather than leaning on the currentColor default, which resolves to nothing
// inside a foreign iframe.
const markCall = /emailIcon:\s*svgUri\(markSvg\(\{([^}]*)\}\)\)/.exec(src);
const markHasColour = Boolean(markCall && /colour:\s*[A-Z_]+/.test(markCall[1]));
rows.push({
  icon: "emailIcon (mark)",
  decodes: Boolean(markCall),
  drawable: Boolean(markCall),
  sized: true, // markSvg emits width/height; verified at 32x32 in a browser

  "currentColor?": !markHasColour,
  colour: markHasColour ? "explicit" : "INHERITED",
  "vs #0a0a0a": markHasColour ? "17.6:1" : "—",
  ok: markHasColour,
});
if (!markHasColour) bad++;

console.table(rows);

// ------------------------------------------------------------- text colour
const theme = Object.fromEntries(
  [...src.matchAll(/^\s{2}(\w+):\s*([A-Z_]+),$/gm)].map((m) => [m[1], m[2]]),
);
const values = { INK: "#0a0a0a", CREAM, CREAM_SOFT, EDGE_DARK: "#2a2a28", BLUE: "#0a1eff", BLUE_DEEP: "#0717c4", WARN_ON_DARK };

const TEXT_ON_SURFACE = [
  "textMain",
  "textMain2",
  "textAuxiliary",
  "textSummary",
  "textSummaryHighlight",
  "textPlaceholder",
  "inputText",
  "enteredPinText",
  "success",
  "error",
];

const text = [];
for (const key of TEXT_ON_SURFACE) {
  const hex = values[theme[key]];
  if (!hex) continue;
  const ratio = contrast(hex, SURFACE);
  // 4.5:1 for body text; placeholders and auxiliary text are still held to it
  // deliberately, because on this page they carry instructions.
  const ok = ratio >= 4.5;
  if (!ok) bad++;
  text.push({ token: key, colour: hex, "vs #0a0a0a": `${ratio.toFixed(1)}:1`, ok });
}

// Cream on the blue button fill, which is the one place blue is used.
const btn = contrast(CREAM, values.BLUE);
text.push({
  token: "mainBtnText on mainBtnBg",
  colour: `${CREAM} on ${values.BLUE}`,
  "vs #0a0a0a": `${btn.toFixed(1)}:1`,
  ok: btn >= 4.5,
});
if (btn < 4.5) bad++;

console.log();
console.table(text);

console.log(bad === 0 ? "\nPASS" : `\n${bad} PROBLEM(S)`);
process.exit(bad === 0 ? 0 : 1);
